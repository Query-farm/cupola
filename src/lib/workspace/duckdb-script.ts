function installLine(name: "vgi" | "grainlift"): string {
  const ext = SHELL_EXTENSIONS.find((e) => e.name === name) ?? { name, source: "community" };
  return `${extensionInstallSql(ext)}; LOAD ${name};`;
}

/** Text safe inside a `--` comment: one line. */
function commentText(text: string): string {
  return text.replace(/[\r\n\u2028\u2029\u0085\v\f]+/g, " ").trim();
}

/** A secret's spec, so `buildAttachSql` emits getenv() for it whatever its
 *  name looks like. */
function secretSpec(name: string): OptionSpecInfo {
  return { name, description: "", duckdbType: "VARCHAR", castType: null, arrowType: "Utf8", required: false, secret: true };
}

/** The workspace as a script for the duckdb CLI. Only enabled catalogs are
 *  attached (a disabled one is named in a comment). Secrets are read from the
 *  environment; their names come from `secretNames` (by default none). */
export function workspaceToDuckdbScript(ws: Workspace, secretNames: SecretNamesOf = () => []): string {
  const enabled = ws.catalogs.filter((c) => c.enabled && c.catalogName && c.alias);
  const lines: string[] = [];
  lines.push(`${HEADER_NAME}${commentText(workspaceLabel(ws))}`);
  lines.push(`${HEADER_ID}${commentText(ws.id)}`);
  lines.push("-- Generated by Cupola. Run with: duckdb -init <this file>");

  const attaches: string[] = [];
  const envVars: string[] = [];
  const skipped: string[] = [];
  for (const c of ws.catalogs) {
    if (!enabled.includes(c)) {
      skipped.push(`--   ${quoteIdent(c.alias || c.catalogName || "catalog")}: ${c.enabled ? "never connected, so the server has not named it" : "disabled in this browser"}`);
      continue;
    }
    const secrets = secretNames(ws, c);
    const lower = new Set(secrets.map((s) => s.toLowerCase()));
    const options: Record<string, string> = {};
    for (const [name, value] of Object.entries(c.options)) if (!lower.has(name.toLowerCase())) options[name] = value;
    for (const name of secrets) if (OPTION_NAME_RE.test(name)) options[name] = "";
    const kind = catalogKind(c.url);
    if (kind === "grainlift" && c.target) options.target = c.target;
    if (c.dataVersionSpec) options.data_version_spec = c.dataVersionSpec;
    const specs = secrets.map(secretSpec);
    for (const name of Object.keys(options)) if (isSecretOption(name, specs)) envVars.push(getenvName(c.alias, name));
    if (c.rawOptions) attaches.push(`-- Not included for ${quoteIdent(c.alias)}: options not yet evaluated (${commentText(c.rawOptions)}).`);
    attaches.push(`${buildAttachSql({ kind, url: c.url, catalogName: c.catalogName, alias: c.alias, options, specs }, "cli")};`);
  }

  if (envVars.length) {
    lines.push("--", "-- Set these environment variables first:");
    for (const v of envVars) lines.push(`--   export ${v}=...`);
  }
  if (skipped.length) {
    lines.push("--", "-- Not attached:");
    lines.push(...skipped);
  }
  lines.push("");
  if (!enabled.length) {
    lines.push("-- This workspace has no catalog to attach.");
    return lines.join("\n") + "\n";
  }
  lines.push(installLine("vgi"));
  if (enabled.some((c) => catalogKind(c.url) === "grainlift")) lines.push(installLine("grainlift"));
  lines.push("", ...attaches, "");
  const def = enabled.find((c) => c.id === ws.defaultCatalogId) ?? enabled[0];
  lines.push(ws.defaultSchema ? `USE ${quoteIdent(def.alias)}.${quoteIdent(ws.defaultSchema)};` : `USE ${quoteIdent(def.alias)};`);
  return lines.join("\n") + "\n";
}

