export type TokenType = "string" | "ident" | "qident" | "number" | "punct";

export interface Token {
  type: TokenType;
  /** Decoded value: a string's text, an identifier's name. */
  value: string;
  /** Source offsets. */
  start: number;
  end: number;
  line: number;
}

export class ScriptError extends Error {
  constructor(readonly line: number, message: string) {
    super(`Line ${line}: ${message}`);
  }
}

const PUNCT = new Set(["(", ")", "[", "]", "{", "}", ",", ";", ".", ":", "-", "+", "*", "/", "=", "<", ">", "!", "%", "|", "&", "^", "~", "?"]);
const OPEN: Record<string, string> = { "(": ")", "[": "]", "{": "}" };

/** Split SQL text into tokens. Handles `'…'` strings and `"…"` identifiers
 *  with doubled-quote escapes, `--` and `/* … *\/` comments, and checks that
 *  brackets balance. Anything it does not know (`$$` strings, backslashes) is
 *  an error rather than a guess. */
export function tokenize(text: string): Token[] {
  const tokens: Token[] = [];
  const stack: { close: string; line: number }[] = [];
  let line = 1;
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (c === "\n") { line++; i++; continue; }
    if (/\s/.test(c)) { i++; continue; }
    if (c === "-" && text[i + 1] === "-") {
      while (i < n && text[i] !== "\n") i++;
      continue;
    }
    if (c === "/" && text[i + 1] === "*") {
      const startLine = line;
      const end = text.indexOf("*/", i + 2);
      if (end < 0) throw new ScriptError(startLine, "a /* comment is never closed.");
      for (let k = i; k < end; k++) if (text[k] === "\n") line++;
      i = end + 2;
      continue;
    }
    if (c === "'" || c === '"') {
      const startLine = line;
      const start = i;
      let value = "";
      i++;
      for (;;) {
        if (i >= n) throw new ScriptError(startLine, c === "'" ? "a string is never closed (unbalanced ')." : "a quoted name is never closed (unbalanced \").");
        const ch = text[i];
        if (ch === c) {
          if (text[i + 1] === c) { value += c; i += 2; continue; }
          i++;
          break;
        }
        if (ch === "\n") line++;
        value += ch;
        i++;
      }
      tokens.push({ type: c === "'" ? "string" : "qident", value, start, end: i, line: startLine });
      continue;
    }
    if (/[A-Za-z_]/.test(c)) {
      const start = i;
      while (i < n && /[A-Za-z0-9_]/.test(text[i])) i++;
      tokens.push({ type: "ident", value: text.slice(start, i), start, end: i, line });
      continue;
    }
    if (/[0-9]/.test(c) || (c === "." && /[0-9]/.test(text[i + 1] ?? ""))) {
      const start = i;
      while (i < n && /[0-9.eE_]/.test(text[i])) {
        if ((text[i] === "e" || text[i] === "E") && /[+-]/.test(text[i + 1] ?? "")) i++;
        i++;
      }
      tokens.push({ type: "number", value: text.slice(start, i), start, end: i, line });
      continue;
    }
    if (PUNCT.has(c)) {
      if (c in OPEN) stack.push({ close: OPEN[c], line });
      else if (c === ")" || c === "]" || c === "}") {
        const open = stack.pop();
        if (!open || open.close !== c) throw new ScriptError(line, `unbalanced brackets: "${c}" closes nothing open.`);
      } else if (c === ";" && stack.length) {
        throw new ScriptError(stack[stack.length - 1].line, `a bracket opened here is not closed before the ";" on line ${line}.`);
      }
      // `::` is one token.
      if (c === ":" && text[i + 1] === ":") {
        tokens.push({ type: "punct", value: "::", start: i, end: i + 2, line });
        i += 2;
        continue;
      }
      tokens.push({ type: "punct", value: c, start: i, end: i + 1, line });
      i++;
      continue;
    }
    throw new ScriptError(line, `unexpected character ${JSON.stringify(c)}.`);
  }
  if (stack.length) throw new ScriptError(stack[stack.length - 1].line, "a bracket opened here is never closed.");
  return tokens;
}

/** Tokens back to SQL text: the source between adjacent tokens is kept when
 *  it is whitespace, and replaced by a space when it held a comment. */
function sourceOf(text: string, tokens: readonly Token[]): string {
  let out = "";
  tokens.forEach((t, i) => {
    if (i > 0) {
      const gap = text.slice(tokens[i - 1].end, t.start);
      out += /^\s*$/.test(gap) ? gap : " ";
    }
    out += text.slice(t.start, t.end);
  });
  return out.trim();
}

