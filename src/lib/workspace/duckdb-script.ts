/**
 * A workspace as a DuckDB script, and back.
 *
 * Export (`workspaceToDuckdbScript`): the extensions' INSTALL/LOAD, one ATTACH
 * per enabled catalog, built by `buildAttachSql` in `cli` mode (the same
 * builder the engine uses, so secrets become `getenv('<ALIAS>_<OPTION>')`
 * and nothing is quoted differently), then `USE "alias"."schema"`. A header
 * comment names the workspace, its id, and the environment variables to set.
 *
 * Import (`parseDuckdbScript`): a script is untrusted text, so the parser
 * accepts a closed set and refuses the rest, line-numbered:
 *
 * - `ATTACH [OR REPLACE] [DATABASE] [IF NOT EXISTS] '<path>' [AS] <ident>
 *   (TYPE vgi|grainlift, LOCATION '<url>', <opt> <value>, …)`
 * - `USE <ident>[.<ident>]`
 * - `INSTALL`/`LOAD` of vgi or grainlift only (what an export writes; they
 *   carry nothing and are skipped). `SET`, `PRAGMA`, other extensions and
 *   every other statement are refused.
 *
 * Option values go through the same rules as the legacy option text
 * (`attach/legacy-options.ts`): plain literals convert here; any other
 * constant expression is kept as raw option text, which the engine checks
 * against the constant allowlist at connect time before it runs (and which a
 * static screen here refuses early when it names a query or a function
 * outside the allowlist). `getenv('X')` makes the option a secret with no
 * value, noted with X. A literal secret in a script is not imported.
 *
 * Pure: unit-tested in tests/unit/workspace-duckdb-script.test.ts.
 */
import { quoteIdent } from "../duckdb-query";
import { extensionInstallSql, SHELL_EXTENSIONS } from "../duckdb-engine";
import { parsePlainLiteral, splitLegacyOptions } from "../attach/legacy-options";
import { buildAttachSql, getenvName, isSecretOption, OPTION_NAME_RE, type OptionSpecInfo } from "../attach/options";
import { assignAliases, isValidAlias } from "./aliases";
import { catalogKind, validateWorkspaceFile, WORKSPACE_FORMAT, WORKSPACE_VERSION, type PortableCatalog, type PortableWorkspace } from "./spec";
import { withIds, type ImportWorkspace, type SecretNamesOf } from "./file";
import { newWorkspaceId, workspaceLabel, type Workspace } from "./store";

export const DUCKDB_SCRIPT_EXTENSION = ".sql";
/** Longer scripts are refused before tokenizing. */
const MAX_SCRIPT_CHARS = 256 * 1024;
const MAX_EXPR_CHARS = 2048;

const HEADER_NAME = "-- Cupola workspace: ";
const HEADER_ID = "-- Workspace id: ";

